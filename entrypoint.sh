#!/usr/bin/env bash
set -euo pipefail

PUID="${PUID:-1000}"
PGID="${PGID:-1000}"
DSH_USER="${DSH_USER:-dsh}"
HOME_DIR="/data"
WORKSPACE="/workspace"
DSH_HOME="${DSH_HOME:-/data/.dsh}"
DSH_PORT="${DSH_PORT:-3080}"

mkdir -p "$HOME_DIR" "$DSH_HOME"

# The image sets no global HOME; export it here so both paths below run with
# HOME=/data. gosu would fall back to the passwd entry, but an explicit value
# also covers arbitrary `--user <uid>` starts with no passwd entry.
export HOME="$HOME_DIR"
export DSH_HOME

# `dsh web` refuses `--host 0.0.0.0` for safety, but the webserver config row
# supports binding all-interfaces. A Harness-home cordis.patch.yml is the
# documented deployment knob for that (and for silently disabling the browser
# handoff). Generate it once if absent so an operator can still hand-edit it;
# delete the file to regenerate from the current environment.
PATCH="$DSH_HOME/cordis.patch.yml"
if [ ! -f "$PATCH" ]; then
    cat > "$PATCH" <<'EOF'
# Generated by the dsh deployment entrypoint on first start. Delete this file
# to regenerate it from the current environment (DSH_PORT/DSH_TRUSTED_HOSTS).
# The webserver row binds all interfaces so the compose port publish reaches the
# harness; the CLI's `--host 0.0.0.0` flag is intentionally rejected, but a
# config patch is the documented deployment channel. The connection row keeps
# the /api browser-trust fence working for loopback hosts plus any extra
# authorities named in DSH_TRUSTED_HOSTS (comma-separated).
- id: webserver
  config:
    host: '0.0.0.0'
    port: !!js Number(process.env.DSH_PORT ?? 3080)

- id: connection
  config:
    trustedHosts: !!js (process.env.DSH_TRUSTED_HOSTS ?? '').split(',').map(s => s.trim()).filter(Boolean).concat(['localhost', '127.0.0.1', '[::1]'])
EOF
    chown "$PUID:$PGID" "$PATCH" 2>/dev/null || true
fi

if [ "$(id -u)" != "0" ]; then
    exec dsh "$@"
fi

if ! getent group "$PGID" > /dev/null 2>&1; then
    if getent group "$DSH_USER" > /dev/null 2>&1; then
        groupmod -o -g "$PGID" "$DSH_USER" 2>/dev/null || true
    else
        groupadd -o -g "$PGID" "$DSH_USER"
    fi
fi

if id "$DSH_USER" > /dev/null 2>&1; then
    usermod -o -u "$PUID" -g "$PGID" -d "$HOME_DIR" "$DSH_USER" 2>/dev/null || true
else
    useradd -o -u "$PUID" -g "$PGID" -d "$HOME_DIR" -s /bin/bash "$DSH_USER"
fi

chown -R "$PUID:$PGID" "$HOME_DIR" "$WORKSPACE" || \
    echo "warning: chown failed for some paths under $HOME_DIR or $WORKSPACE (read-only mounts?)"

# Hand the mise dir (tools installed at build time as root) to the runtime
# user so `mise install` for a new version works without sudo.
chown -R "$PUID:$PGID" "${MISE_DATA_DIR:-/mise}" 2>/dev/null || \
    echo "warning: could not chown mise dir ${MISE_DATA_DIR:-/mise}"

exec gosu "$PUID:$PGID" /usr/local/bin/dsh "$@"
